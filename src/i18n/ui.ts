export const LANGUAGE_BY_CODE: Record<LangCode, LanguageOption> = Object.fromEntries(
  SUPPORTED_LANGUAGES.map((l) => [l.code, l]),
) as Record<LangCode, LanguageOption>;

export function detectBrowserLang(): LangCode {
  if (typeof navigator === 'undefined') return 'en';
  const raw = (navigator.language || '').toLowerCase();
  if (raw.startsWith('ar')) return 'ar';
  if (raw.startsWith('de')) return 'de';
  if (raw.startsWith('nl')) return 'nl';
  if (raw === 'es' || raw === 'es-es') return 'es';
  if (raw.startsWith('es-')) return 'es-419';
  if (raw.startsWith('fr')) return 'fr';
  if (raw.startsWith('it')) return 'it';
  if (raw.startsWith('pt')) return 'pt';
  if (raw.startsWith('yue') || raw === 'zh-hk' || raw === 'zh-mo') return 'yue';
  if (raw.startsWith('zh')) return 'zh';
  if (raw.startsWith('ja')) return 'ja';
  if (raw.startsWith('ko')) return 'ko';
  return 'en';
}

export function applyDocumentLang(lang: LangCode): void {
  if (typeof document === 'undefined') return;
  const meta = LANGUAGE_BY_CODE[lang] ?? LANGUAGE_BY_CODE.en;
  document.documentElement.lang = meta.code === 'yue' ? 'yue-Hant-HK' : meta.code;
  document.documentElement.dir = meta.dir;
}

