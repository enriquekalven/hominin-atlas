/** Rotate answers by a deterministic per-question offset; recompute correctIndex accordingly. */
function rotate(q: QuizQuestion, i: number): QuizQuestion {
  const n = q.answers.length;
  const shift = (i * 7 + 2) % n;
  const answers = new Array<string>(n);
  q.answers.forEach((a, j) => {
    answers[(j + shift) % n] = a;
  });
  return { ...q, answers, correctIndex: (q.correctIndex + shift) % n };
}

export const QUIZ: QuizQuestion[] = AUTHORED.map(rotate);
